async def send_admin_report(bot, cfg, db):
    if os.getenv('RAILWAY_PROJECT_ID') != 'aae9ee4d-e392-46a9-892a-f656adc80955':
        return
    for admin in cfg.admin_ids:
        key = 'zero-research:v1:admin:'+str(admin)
        if await db.kv_get(key+':receipt'):
            continue
        # Fence against duplicate workers/restarts and ambiguous network outcomes.
        if not await db.claim_slot(key+':attempt'):
            continue
        sent = await bot.send_message(admin, ADMIN_REPORT, parse_mode=None,
                                      disable_web_page_preview=True)
        await db.kv_set(key+':receipt', json.dumps({'chat_id':admin,'message_id':sent.message_id}))
