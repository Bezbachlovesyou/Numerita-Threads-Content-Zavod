"""Третий механизм продажи личного разбора (слово владельца 31.10.2026: «личное нельзя получить общим постом — время рождения, пара,
год; начинаем использовать на максимум»): общий пост даёт полноценный дар и честно упирается в то, чего у него нет — год (число судьбы),
время и город (рассвет), пара (две даты). Петля закрывается в личном чате, а не в комментариях: полную дату публично не просим.

Здесь — проверенные кодом примеры для рубрик (модель сама арифметику не считает) и гарантия частоты: не реже, чем раз в 3 поста —
пост из набора PERSONAL с вероятностью PERSONAL_SHARE (около четверти ленты)."""

import random
from datetime import date

from .knowledge import reduce_number

# Рубрики третьего механизма: год, пара, время рождения (рассвет), «ищу…», «чего не знает общий пост».
PERSONAL = ("text_year", "text_pair", "text_sunrise", "text_seek", "text_unknown")
PERSONAL_SHARE = 0.18  # если в последних трёх постах такого не было — берём из набора с этой вероятностью


def destiny(day: int, month: int, year: int) -> int:
    """Число судьбы по базе Нумериты: сумма всех цифр даты ДД.ММ.ГГГГ, сведённая к одной цифре."""
    return reduce_number(sum(int(c) for c in f"{day:02d}{month:02d}{year}"))


def year_example(rng: random.Random) -> str:
    """Один день рождения, ТРИ разных года, три РАЗНЫХ числа судьбы («Три года — три дороги»): «14.05.1985 → 6; 14.05.1992 → 4; 14.05.2001 → 3»."""
    while True:
        month, d = rng.randint(1, 12), rng.randint(1, 28)
        years = sorted(rng.sample(range(1960, 2008), 3))
        nums = [destiny(d, month, y) for y in years]
        if len(set(nums)) == 3:
            break
    parts = [f"{d:02d}.{month:02d}.{y} → сумма цифр {sum(int(c) for c in f'{d:02d}{month:02d}{y}')} → число судьбы {n}" for y, n in zip(years, nums)]
    return "; ".join(parts) + f"; число души у всех троих {reduce_number(d)} (день {d})"
