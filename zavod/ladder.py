"""«Лестница личного» — переход от бесплатной общей пользы к платному личному (слово владельца 31.10.2026: усилить слабое звено
цепочки, применив анализ, синтез, сравнение, абстракцию, обобщение и конкретизацию, не нарушая сути Нумериты).

Суть: человек платит не за «разбор вообще», а когда почувствовал «это про меня» и видит честное СЛЕДУЮЩЕЕ звено — то, что по его
данным действительно нельзя узнать без ещё одного его ввода. Поэтому ответ: (1) полноценный дар по тому, что он назвал (число души,
планета, одна точная деталь), (2) одна честная фраза: чего по такому набору данных не видно и от чего оно зависит (полная дата →
число судьбы; время и город → день по традиции начинается на рассвете и число может сдвинуться; имя → число имени; дата близкого →
совместимость), (3) спокойное приглашение собрать это личной картой в боте. Без давления, цены, дефицита и обещаний.

Код считает, что человек уже дал, и подсказывает, чего не хватает; нейросеть выбирает одно самое интересное и говорит по-человечески.
Вариант идёт в метку ссылки (…_l — «лестница», …_m — «лестница, последний бесплатный ответ»; старые: …_o, …_w), чтобы воронка сравнила
оба по людям в боте и оплатам, а не по ощущению. Доля «лестницы» — kv ladder:share (по умолчанию 0,5)."""

import re
import zlib

from .codereply import find_birth, find_pair

TIME_RE = re.compile(r"\b\d{1,2}[:.]\d{2}\b|\b(?:утра|ночи|вечера|дня)\b|\bв\s+\d{1,2}\s*(?:час|ч\b)|\b(?:am|pm|a\.m\.|p\.m\.)\b", re.I)
LETTERS = {("link", "base"): "a", ("offer", "base"): "o", ("paywall", "base"): "w",
           ("link", "ladder"): "a", ("offer", "ladder"): "l", ("paywall", "ladder"): "m"}
DEFAULT_SHARE = 0.5


def variant_for(comment_id, share: float = DEFAULT_SHARE) -> str:
    """Какой вариант приглашения получает этот комментарий: детерминированно по номеру, доля «лестницы» — share."""
    return "ladder" if zlib.crc32(str(comment_id).encode()) % 100 < int(share * 100) else "base"


def letter(mode: str, variant: str) -> str:
    """Буква режима в метке ссылки ответа."""
    return LETTERS.get((mode, variant), "a")


def hint(comment: str) -> str:
    """Что человек уже дал и что глубже раскрывается с ещё одним его вводом (считает код, не нейросеть)."""
    text = (comment or "").replace("?", " ")
    pair, birth = find_pair(comment or ""), find_birth(text)
    missing = []
    if pair:
        given = "две даты рождения (пара)"
        missing += ["время рождения у каждого: день по традиции начинается на рассвете, и число может сдвинуться",
                    "имена: у каждого есть ещё и число имени"]
    elif birth:
        day, month, year = birth
        given = "день рождения" + (" и месяц" if month else "") + (" и год" if year else "")
        if not year:
            missing.append("полная дата с годом: по ней считается число судьбы (миссии)")
        if not TIME_RE.search(text):
            missing.append("время и город рождения: день по традиции начинается на рассвете, и число может сдвинуться")
        missing.append("имя: у человека есть и число имени")
        missing.append("дата близкого человека: из двух дат получается совместимость пары")
    else:
        given = "число или общий вопрос"
        missing += ["день рождения: по нему считается число души", "полная дата: по ней считается число судьбы"]
    return f"Человек уже дал: {given}. Глубже раскрывается с: " + "; ".join(missing) + "."


def note(mode: str, comment: str) -> str:
    """Добавка к заданию ответа для варианта «лестница» (режимы offer и paywall)."""
    if mode not in ("offer", "paywall"):
        return ""
    return (
        "\n\nЛЕСТНИЦА ЛИЧНОГО (порядок ответа). 1) Сначала настоящий дар по тому, что человек назвал: число души и планета и ОДНА "
        "точная неожиданная деталь именно про него (сила или тень), живо, тепло, с искрой юмора — ответ ценен и без ссылки. "
        "2) Затем одной фразой честно скажи, что по такому набору данных видно не всё. " + hint(comment) + " Выбери ОДНО, самое "
        "интересное для этого человека, и по-человечески, без терминов, назови, что именно оно меняет. Это правило традиции, а не "
        "гарантия и не предсказание. 3) Последняя фраза — спокойное приглашение собрать это в личную карту у Нумериты в Telegram "
        "(как в задании). Без давления, без «купи», без цены, без дефицита («осталось мест», «последний шанс»), без обещаний "
        "любви, денег и будущего.")
